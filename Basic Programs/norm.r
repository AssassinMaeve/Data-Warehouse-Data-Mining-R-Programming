# Normal Distribution

# Calculates the cumulative probability (P(X ≤ 5)) for a normal distribution 
# with mean = 5 and standard deviation = 1
pnorm(5, mean = 5, sd = 1)

# Calculates the quantile (value of X) corresponding to a cumulative probability of 0.5
# for a normal distribution with mean = 5 and standard deviation = 1
qnorm(0.5, mean = 5, sd = 1)

# Randomly generates a single number from a normal distribution 
# with mean = 0 and standard deviation = 1
rnorm(n = 1)